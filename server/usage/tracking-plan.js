/** The one-line answer to "what is NOT collected", repeated at the top of the generated page. */
export const NEVER = 'No site, address, title, task, note, goal, time of day, IP address, account or name — ever.';

/** The generated document. */
export function renderTrackingPlan(/** @type {string[]} */ features, /** @type {string[]} */ flags) {
  const row = (/** @type {string} */ id, /** @type {Record<string, [string, string]>} */ plan) => `| \`${id}\` | ${plan[id][0]} | ${plan[id][1]} |`;
  return [
    '<!-- Generated by scripts-dev/tracking-plan.mjs from server/usage/tracking-plan.js. Do not edit by hand. -->',
    '# Tracking plan',
    '',
    'Everything the optional anonymous usage report can carry, one row per name, with where the collector\'s dashboard reads it. Nothing else can be sent: the schema (`src/shared/usage-schema.js`) refuses it on the device and again on the collector.',
    '',
    `**${NEVER}**`,
    '',
    '## Counters (uses since the last report)',
    '',
    '| Name | Counted when | Read on |',
    '|---|---|---|',
    ...features.map((f) => row(f, FEATURE_PLAN)),
    '',
    '## Setup flags (what is switched on)',
    '',
    '| Name | Meaning | Read on |',
    '|---|---|---|',
    ...flags.map((f) => row(f, FLAG_PLAN)),
    '',
    '## Also on the report',
    '',
    '| Field | Meaning |',
    '|---|---|',
    '| `age`, `act` | Whole days since the install, and the ages on which EyeTime was used. Never a date. |',
    '| `first` | The age at which each counter was first used (the activation funnel). |',
    '| `app`, `br`, `os`, `lang`, `look`, `layout`, `mode` | Version, browser family, system family, language, look, layout and light / dark / auto. |',
    '| `x` | Only while an experiment runs: the arm this device was put in (`id:arm`). The random number that chose it never leaves the device. |',
    '',
    '## Not on the report, counted by the collector',
    '',
    '- **Intake**: how many reports were accepted or refused per day and why (no identifier).',
    '- **Removal reasons**: one reason from a fixed list per answer on the page that opens after removal, counted by day (no identifier).',
    '',
  ].join('\n');
}

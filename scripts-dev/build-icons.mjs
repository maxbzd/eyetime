// Generates src/ui/icons.js: only the Lucide icons the code actually references.
//
//   npm i --no-save lucide-static && node scripts-dev/build-icons.mjs
//
// An icon is "referenced" when the source contains  icon('name')  icon("name")  data-icon="name"  or  icon: 'name'.
// Names must be literals somewhere in the code (use  icon: 'name'  in data tables for dynamic cases).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const lucideDir = process.argv[2] || path.join(root, 'node_modules/lucide-static/icons');
if (!fs.existsSync(lucideDir)) { console.error('lucide-static not found. Run: npm i --no-save lucide-static'); process.exit(1); }

const names = new Set();
const re = /(?:icon\(\s*['"`]|data-icon=["']|\bicon:\s*['"`]|\bico:\s*['"`])([a-z0-9-]+)['"`]?/g;
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) { if (f !== 'fonts') walk(p); continue; }
    if (!/\.(js|html|mjs)$/.test(f) || f === 'icons.js') continue;
    const src = fs.readFileSync(p, 'utf8');
    for (const m of src.matchAll(re)) names.add(m[1]);
    for (const call of src.matchAll(/\bicon\(([^()]*)\)/g)) for (const q of call[1].matchAll(/'([a-z][a-z0-9-]*)'/g)) names.add(q[1]); // conditionals: icon(a ? 'x' : 'y')
  }
})(path.join(root, 'src'));

const out = {};
const missing = [];
names.delete('name'); // appears in doc comments
for (const n of [...names].sort()) {
  const file = path.join(lucideDir, n + '.svg');
  if (!fs.existsSync(file)) { missing.push(n); continue; }
  const svg = fs.readFileSync(file, 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').replace(/> </g, '><').trim();
  out[n] = inner;
}
if (missing.length) console.warn('Unknown icons (skipped):', missing.join(', '));

const body = `// GENERATED by scripts-dev/build-icons.mjs — do not edit. Icons: Lucide (ISC), see LICENSE-Lucide.txt.\nexport const ICONS = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(path.join(root, 'src/ui/icons.js'), body);
console.log(`icons.js: ${Object.keys(out).length} icons`);
